// Elapsed time, rather than interval counts, keeps phases accurate after a tab sleeps.
export function clockState(phases:Phase[],elapsedMs:number) {
  let left=Math.max(0,elapsedMs);
  for(let i=0;i<phases.length;i++) {
    const duration=phases[i].seconds*1000;
    if(left<duration)return {phase:i,remaining:Math.ceil((duration-left)/1000),done:false};
    left-=duration;
  }
  return {phase:phases.length-1,remaining:0,done:true};
}
